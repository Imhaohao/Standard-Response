// Bakes the hazard scenarios the maps draw (data/hazard, via /api/scenario) into convex/scenarioFronts.ts,
// so Convex can measure every home's fire arrival against the same fronts. Convex can't read files or
// import .geojson, hence the copy. Run after a scenario changes: `npx tsx scripts/hazard/bake-scenarios.ts`.
// `npm run test:hazard` fails while the baked copy is out of date.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { HAZARDS, SCENARIO_FILES } from "../../convex/hazards";

const ROOT = join(import.meta.dirname, "..", "..");
export const BAKED_FILE = join(ROOT, "convex", "scenarioFronts.ts");

type Ring = number[][];
type Feature = { properties: { minutesAfterWarning: number }; geometry: { type: "Polygon"; coordinates: Ring[] } | { type: "MultiPolygon"; coordinates: Ring[][] } };

// Six decimals of a degree is about 10 cm: well under anything the map can show.
const round = (value: number) => Math.round(value * 1e6) / 1e6;
const roundRings = (rings: Ring[]) => rings.map((ring) => ring.map(([lng, lat]) => [round(lng), round(lat)]));

function trimmed(feature: Feature): Feature {
  const { minutesAfterWarning } = feature.properties;
  const { geometry } = feature;
  if (geometry.type === "Polygon") return { properties: { minutesAfterWarning }, geometry: { type: "Polygon", coordinates: roundRings(geometry.coordinates) } };
  return { properties: { minutesAfterWarning }, geometry: { type: "MultiPolygon", coordinates: geometry.coordinates.map(roundRings) } };
}

export function bakedSource() {
  const scenarios: Record<string, { features: Feature[] }> = {};
  for (const hazard of HAZARDS) {
    const path = join(ROOT, "data", "hazard", SCENARIO_FILES[hazard]);
    if (!existsSync(path)) continue;
    const geojson = JSON.parse(readFileSync(path, "utf8")) as { features: Feature[] };
    scenarios[hazard] = { features: geojson.features.map(trimmed) };
  }
  return [
    "// Generated by scripts/hazard/bake-scenarios.ts from data/hazard. Don't edit; rerun the script.",
    'import type { ScenarioGeoJson } from "../lib/ink-map/fire-field";',
    'import type { Hazard } from "./hazards";',
    "",
    `export const SCENARIO_FRONTS: Partial<Record<Hazard, ScenarioGeoJson>> = ${JSON.stringify(scenarios)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(BAKED_FILE, bakedSource());
  console.log(`Wrote ${BAKED_FILE}`);
}
